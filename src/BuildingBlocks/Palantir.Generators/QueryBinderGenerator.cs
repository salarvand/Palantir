using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Palantir.Generators;

[Generator]
public class QueryBinderGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var classDeclarations = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (s, _) => s is ClassDeclarationSyntax c && c.AttributeLists.Count > 0,
                transform: static (ctx, _) => GetSemanticTargetForGeneration(ctx))
            .Where(static m => m is not null);

        context.RegisterSourceOutput(classDeclarations, static (spc, source) =>
        {
            if (source is null) return;
            var code = GenerateQueryBinder(source);
            spc.AddSource($"{source.Name}QueryBinder.g.cs", SourceText.From(code, Encoding.UTF8));
        });
    }

    private static INamedTypeSymbol? GetSemanticTargetForGeneration(GeneratorSyntaxContext context)
    {
        var classDeclaration = (ClassDeclarationSyntax)context.Node;
        var model = context.SemanticModel;
        var symbol = model.GetDeclaredSymbol(classDeclaration) as INamedTypeSymbol;
        if (symbol == null) return null;

        foreach (var attribute in symbol.GetAttributes())
        {
            if (attribute.AttributeClass?.Name is "QueryBindableAttribute" or "QueryBindable")
            {
                return symbol;
            }
        }

        return null;
    }

    private static string GenerateQueryBinder(INamedTypeSymbol symbol)
    {
        var ns = symbol.ContainingNamespace.ToDisplayString();
        var className = symbol.Name;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine($"public static class {className}BinderExtensions");
        sb.AppendLine("{");
        sb.AppendLine($"    public static {className} FromQuery(Microsoft.AspNetCore.Http.IQueryCollection query)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var result = new {className}();");

        foreach (var member in symbol.GetMembers().OfType<IPropertySymbol>())
        {
            if (member.SetMethod is null) continue;
            var propName = member.Name;
            var propType = member.Type.ToDisplayString();

            if (propType == "string" || propType == "string?")
            {
                sb.AppendLine($"        if (query.TryGetValue(\"{propName.ToLowerInvariant()}\", out var {propName}Val)) result.{propName} = {propName}Val.ToString();");
            }
            else if (propType == "int" || propType == "int?")
            {
                sb.AppendLine($"        if (query.TryGetValue(\"{propName.ToLowerInvariant()}\", out var {propName}Val) && int.TryParse({propName}Val, out var {propName}Parsed)) result.{propName} = {propName}Parsed;");
            }
            else if (propType == "decimal" || propType == "decimal?")
            {
                sb.AppendLine($"        if (query.TryGetValue(\"{propName.ToLowerInvariant()}\", out var {propName}Val) && decimal.TryParse({propName}Val, out var {propName}Parsed)) result.{propName} = {propName}Parsed;");
            }
        }

        sb.AppendLine("        return result;");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }
}
